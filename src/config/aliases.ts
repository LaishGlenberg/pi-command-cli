import { dirname, join } from "node:path";

import { ALIASES_FILENAME } from "../constants.ts";
import { shellQuote } from "../cli/arguments.ts";
import { configPath, writeFileAtomic } from "./config-file.ts";

// Conservative, portable shell alias name. Alias names with spaces, quotes, or
// other metacharacters are skipped (and reported) rather than emitted broken.
const ALIAS_NAME = /^[A-Za-z_][A-Za-z0-9_.-]*$/;

// Shell reserved words and builtins. An alias with one of these names still
// works in an interactive shell (aliases expand before builtins), but in a
// non-interactive shell (`shopt -u expand_aliases`) bash ignores the alias and
// runs the builtin instead, often silently. These are reported, not skipped.
export const SHELL_BUILTINS: ReadonlySet<string> = new Set([
  // Reserved words.
  "if", "then", "else", "elif", "fi", "for", "while", "until", "do", "done",
  "case", "esac", "in", "function", "select", "time", "coproc",
  // Builtins.
  "alias", "bg", "bind", "break", "builtin", "caller", "cd", "command",
  "compgen", "complete", "compopt", "continue", "declare", "dirs", "disown",
  "echo", "enable", "eval", "exec", "exit", "export", "false", "fc", "fg",
  "getopts", "hash", "help", "history", "jobs", "kill", "let", "local",
  "logout", "mapfile", "popd", "printf", "pushd", "pwd", "read", "readarray",
  "readonly", "return", "set", "shift", "shopt", "source", "suspend", "test",
  "times", "trap", "true", "type", "typeset", "ulimit", "umask", "unalias",
  "unset", "wait",
]);

export function isValidAliasName(name: string): boolean {
  return ALIAS_NAME.test(name);
}

/** Whether an alias name collides with a shell reserved word or builtin. */
export function isShellBuiltin(name: string): boolean {
  return SHELL_BUILTINS.has(name);
}

/**
 * Absolute path to the generated shell alias file. It lives next to the config
 * file, so `$PI_CLI_CONFIG` (and a temp config dir in tests) moves it too.
 */
export function aliasesPath(configFilePath?: string): string {
  return join(dirname(configFilePath ?? configPath()), ALIASES_FILENAME);
}

export interface FormattedAliases {
  content: string;
  skipped: string[];
  shadowed: string[];
}

/**
 * Render the `agents` map as POSIX shell aliases. Each valid name becomes
 * `alias <name>='pi-cli -i <name>'`, sorted for stable regeneration. Names that
 * are not valid shell identifiers are collected in `skipped`; valid names that
 * shadow a shell builtin are collected in `shadowed` (still emitted, since
 * they work interactively).
 */
export function formatAliases(agents: Record<string, unknown>): FormattedAliases {
  const skipped: string[] = [];
  const shadowed: string[] = [];
  const names = Object.keys(agents).sort();
  const lines = [
    "# Generated by pi-cli. Do not edit; saved configurations are synced here.",
  ];

  for (const name of names) {
    const command = agents[name];
    if (typeof command !== "string") continue;
    if (!isValidAliasName(name)) {
      skipped.push(name);
      continue;
    }
    if (isShellBuiltin(name)) shadowed.push(name);
    lines.push(`alias ${name}=${shellQuote(`pi-cli -i ${name}`)}`);
  }

  return { content: `${lines.join("\n")}\n`, skipped, shadowed };
}

export interface WrittenAliases {
  path: string;
  skipped: string[];
  shadowed: string[];
}

/**
 * Write the alias file for the given `agents` map. Always rewrites the whole
 * file so it stays in sync with the config (the config is the source of truth).
 */
export function writeAliases(
  agents: Record<string, unknown>,
  configFilePath?: string,
): WrittenAliases {
  const path = aliasesPath(configFilePath);
  const { content, skipped, shadowed } = formatAliases(agents);
  writeFileAtomic(path, content);
  return { path, skipped, shadowed };
}

/** Human-readable warnings for skipped and builtin-shadowing alias names. */
export function formatAliasWarnings(
  skipped: readonly string[],
  shadowed: readonly string[] = [],
): string {
  const lines = skipped.map(
    (name) => `pi-cli: warning: skipped alias "${name}" (not a valid shell alias name)\n`,
  );
  lines.push(
    ...shadowed.map(
      (name) =>
        `pi-cli: warning: alias "${name}" shadows a shell builtin and is ignored in non-interactive shells\n`,
    ),
  );
  return lines.join("");
}
